"""Independent local scientific recomputation probe for the frozen Manavgat result.

WHAT THIS IS -- AND HOW IT DIFFERS FROM THE REPLAY
--------------------------------------------------
`reference_replay.py` proved that the regional WRAPPER preserves the frozen
Manavgat science: it reused the frozen `model/` and `compare/` artefacts and
compared the wrapper's projection of them against the originals.

This module answers a different question:

    re-running the fit and the comparison for real, from the frozen local
    inputs, does the SAME science come out?

So here the frozen `model/` and `compare/` trees are NEVER copied. They are
regenerated by the production stage functions:

* ``run_model_stage``   -- common cohort, shared spatial folds, 30 random-forest
                           fits, out-of-fold predictions, point metrics, thermal
                           contributions, and ONE paired spatial-block bootstrap
                           of 1000 draws.
* ``run_compare_stage`` -- every comparison table, the bootstrap evidence matrix
                           and the descriptive report.

Everything upstream of the fit is REUSED from the frozen tree (verified copy):
plan documents, the pre-label censor raster, the exported predictor rasters and
the whole local-downstream chain including the three Step8A datasets. No Earth
Engine call, no remote export and no download happens at any point.

WHY THE STAGE BINDING IS CONSTRUCTED RATHER THAN ASSERTED
---------------------------------------------------------
``run_analysis`` reaches the model stage through ``assert_model_binding``, which
requires every upstream provenance document to carry THIS run's ``analysis_id``
and to record paths inside THIS run's namespace. The frozen documents carry the
analysis id of the original run -- `compute_analysis_id` folds `git_commit` into
the identity, so a run today can never reproduce it -- and they record absolute
paths into the frozen namespace.

Making that assertion pass would mean rewriting the recorded `analysis_id` and
roughly 170 recorded artefact paths inside the frozen export-provenance
documents. Rewriting export provenance so that a verification passes would
destroy the very thing the probe is meant to establish, so it is NOT done.

Instead this module resolves `model_datasets` itself -- verifying each dataset
against the SHA-256 its own producing stage recorded -- and hands that binding
to the real, unmodified ``run_model_stage``. The compare binding then replicates
``assert_compare_binding``'s post-model block verbatim against the freshly
written model tree. The scientific code paths are the production ones; only the
provenance-identity assertions that cannot hold across analysis ids are
replaced by an explicit, hash-verified equivalent.

Design references
-----------------
src/window_closure_sensitivity.py:8996  run_model_stage
src/window_closure_sensitivity.py:10540 run_compare_stage
src/window_closure_sensitivity.py:9776  assert_compare_binding (replicated block)
"""
