def build_model_binding(
    *, experiment_id: str, variants: Sequence[Mapping[str, Any]],
    probe_root: Path, experiments_root: Optional[Path] = None,
) -> dict[str, Any]:
    """`model_datasets` resolved and hash-verified inside the probe namespace.

    Mirrors the dataset half of ``assert_model_binding``. Every shifted dataset
    is checked against the SHA-256 its own local-downstream metadata recorded,
    and the canonical Step8A is checked against the central frozen anchor, so a
    silently different input cannot reach the fit.
    """
    from src.multi_region_window_closure.inputs import CANONICAL_STEP8A_SHA256
    from src.window_closure_sensitivity import (
        CANONICAL_VARIANT_ID, canonical_step8a_path, canonical_step8a_stats_path,
        local_downstream_metadata_path, nonzero_variants,
        variant_step8a_dataset_path, variant_step8a_stats_path,
    )

    def _require(condition: bool, message: str) -> None:
        if not condition:
            raise RecomputeProbeError(f"BLOCKER: PROBE_MODEL_BINDING -- {message}")

    canonical_dataset = canonical_step8a_path(experiment_id, experiments_root)
    canonical_stats = canonical_step8a_stats_path(experiment_id, experiments_root)
    _require(canonical_dataset.is_file(), f"canonical Step8A missing at {canonical_dataset}.")
    _require(canonical_stats.is_file(), f"canonical Step8A stats missing at {canonical_stats}.")
    canonical_sha256 = sha256_path(canonical_dataset)
    _require(
        canonical_sha256 == CANONICAL_STEP8A_SHA256[experiment_id],
        f"canonical Step8A hashes {canonical_sha256}, central anchor is "
        f"{CANONICAL_STEP8A_SHA256[experiment_id]}.",
    )

    datasets: dict[str, dict[str, Any]] = {
        CANONICAL_VARIANT_ID: {
            "variant_id": CANONICAL_VARIANT_ID, "is_canonical": True,
            "dataset_path": str(canonical_dataset),
            "dataset_sha256": canonical_sha256,
            "stats_path": str(canonical_stats),
            "stats_sha256": sha256_path(canonical_stats),
            "source": "frozen canonical production Step8A (read-only)",
        },
    }
    pinned: set[Any] = set()
    for variant in nonzero_variants(list(variants)):
        variant_id = variant["variant_id"]
        metadata_path = local_downstream_metadata_path(experiment_id, variant_id, probe_root)
        _require(metadata_path.is_file(), f"'{variant_id}' local-downstream metadata missing.")
        metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
        _require(metadata.get("status") == "pass",
                 f"'{variant_id}' local-downstream status is {metadata.get('status')!r}.")
        _require(metadata.get("experiment_id") == experiment_id,
                 f"'{variant_id}' local-downstream names another experiment.")
        _require(metadata.get("variant_id") == variant_id,
                 f"'{variant_id}' local-downstream names another variant.")
        dataset_path = variant_step8a_dataset_path(experiment_id, variant_id, probe_root)
        stats_path = variant_step8a_stats_path(experiment_id, variant_id, probe_root)
        _require(dataset_path.is_file(), f"'{variant_id}' Step8A missing at {dataset_path}.")
        _require(stats_path.is_file(), f"'{variant_id}' Step8A stats missing at {stats_path}.")
        digest = sha256_path(dataset_path)
        _require(
            digest == metadata.get("step8a_dataset_sha256"),
            f"'{variant_id}' Step8A hashes {digest} but its local-downstream "
            f"metadata recorded {metadata.get('step8a_dataset_sha256')!r}.",
        )
        _require(
            sha256_path(stats_path) == metadata.get("step8a_stats_sha256"),
            f"'{variant_id}' Step8A stats hash differs from its metadata.",
        )
        pinned.add(metadata.get("canonical_step8a_sha256"))
        datasets[variant_id] = {
            "variant_id": variant_id, "is_canonical": False,
            "shift_days": int(variant["shift_days"]),
            "dataset_path": str(dataset_path), "dataset_sha256": digest,
            "stats_path": str(stats_path), "stats_sha256": sha256_path(stats_path),
            "local_downstream_metadata_path": str(metadata_path),
            "local_downstream_metadata_sha256": sha256_path(metadata_path),
            "source": "window-closure local downstream (status=pass, reused frozen)",
        }
    _require(pinned == {canonical_sha256},
             f"local-downstream pinned canonical hash(es) {sorted(map(str, pinned))}.")
    _require(len(datasets) == len(VARIANTS),
             f"resolved {len(datasets)} datasets, expected {len(VARIANTS)}.")
    return {"model_datasets": datasets, "canonical_step8a_sha256": canonical_sha256}


def build_compare_binding(
    *, experiment_id: str, analysis_id: str, probe_root: Path,
    model_binding: Mapping[str, Any],
) -> dict[str, Any]:
    """Replicates the post-model block of ``assert_compare_binding`` verbatim."""
    from src.window_closure_sensitivity import (
        MODEL_FAMILIES, MODEL_METADATA_SCHEMA, MODEL_STAGE_REQUIRED_FLAGS,
        compare_variant_order, model_metadata_path, model_relative_layout,
        model_root, model_variant_oof_relpath, read_model_stage_metadata,
        sha256_file,
    )

    def _require(condition: bool, message: str) -> None:
        if not condition:
            raise RecomputeProbeError(f"BLOCKER: PROBE_COMPARE_BINDING -- {message}")

    metadata = read_model_stage_metadata(experiment_id, probe_root)
    metadata_path = model_metadata_path(experiment_id, probe_root)
    _require(metadata.get("schema_version") == MODEL_METADATA_SCHEMA,
             f"model schema is {metadata.get('schema_version')!r}.")
    _require(metadata.get("status") == "pass",
             f"model status is {metadata.get('status')!r}.")
    _require(metadata.get("analysis_id") == analysis_id, "model analysis_id mismatch.")
    _require(metadata.get("experiment_id") == experiment_id, "model experiment_id mismatch.")
    for flag, expected in MODEL_STAGE_REQUIRED_FLAGS.items():
        _require(metadata.get(flag) is expected,
                 f"model metadata {flag}={metadata.get(flag)!r}, expected {expected!r}.")

    root = model_root(experiment_id, probe_root)
    layout = model_relative_layout()
    required = [layout[key] for key in sorted(layout) if key != "metadata"]
    recorded = {
        str(record.get("relative_path")): record
        for record in (metadata.get("artifact_inventory") or [])
    }
    for relative in required:
        _require(relative in recorded, f"model metadata records no artefact for '{relative}'.")
    variant_ids = compare_variant_order(sorted(metadata.get("variant_ids") or []))
    for variant_id in variant_ids:
        for family in MODEL_FAMILIES:
            relative = model_variant_oof_relpath(variant_id, family)
            _require(relative in recorded, f"model metadata records no artefact for '{relative}'.")

    artifacts: dict[str, dict[str, Any]] = {}
    for relative, record in sorted(recorded.items()):
        path = Path(str(record.get("path") or ""))
        _require(path.is_file(), f"model artefact '{relative}' is missing at {path}.")
        digest = sha256_file(path)
        _require(digest == record.get("sha256"), f"model artefact '{relative}' hash mismatch.")
        _require(root in path.resolve().parents, f"model artefact '{relative}' lies outside {root}.")
        artifacts[relative] = {
            "relative_path": relative, "path": str(path), "sha256": digest,
            "bytes": int(path.stat().st_size),
        }
    return {
        **dict(model_binding),
        "bound_to_model": True,
        "model_stage_metadata": metadata,
        "model_stage_metadata_path": str(metadata_path),
        "model_stage_metadata_sha256": sha256_file(metadata_path),
        "model_artifacts": artifacts,
        "model_variant_ids": variant_ids,
    }


