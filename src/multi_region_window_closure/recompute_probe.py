def materialize_upstream(frozen_source: Path, probe_root: Path) -> dict[str, Any]:
    """Copy every pre-fit frozen artefact into the probe, verifying each copy.

    `model/` and `compare/` are deliberately excluded: regenerating them is the
    whole point of the probe, and a copy would silently answer the question.
    """
    frozen_source, probe_root = Path(frozen_source), Path(probe_root)
    partition = partition_frozen_source(frozen_source)
    target_root = probe_root / REFERENCE_AOI
    records: list[dict[str, str]] = []
    for stage in REUSED_FROZEN_STAGES:
        for relative in partition[stage]:
            source = frozen_source / relative
            destination = target_root / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, destination)
            source_hash = sha256_path(source)
            if sha256_path(destination) != source_hash:
                raise RecomputeProbeError(
                    "BLOCKER: UPSTREAM_REUSE_HASH_MISMATCH -- "
                    f"{relative} did not copy byte-identically."
                )
            records.append({
                "stage": stage, "relative_path": str(relative),
                "sha256": source_hash, "size_bytes": str(source.stat().st_size),
            })
    excluded = sorted(
        str(relative) for stage in RECOMPUTED_STAGES for relative in partition[stage]
    )
    for tree in RECOMPUTED_TREES:
        if (target_root / tree).exists():
            raise RecomputeProbeError(
                f"BLOCKER: RECOMPUTED_TREE_PRESEEDED -- '{tree}/' exists in the "
                "probe before recomputation; the probe refuses to compare a copy "
                "against its own source."
            )
    return {
        "probe_root": str(probe_root),
        "experiment_root": str(target_root),
        "reused_stages": list(REUSED_FROZEN_STAGES),
        "reused_artifact_count": len(records),
        "reused_artifact_bytes": sum(int(r["size_bytes"]) for r in records),
        "reused_artifacts": records,
        "excluded_frozen_artifact_count": len(excluded),
        "excluded_frozen_artifacts": excluded,
        "recomputed_stages": list(RECOMPUTED_STAGES),
        "gee_queries_run": False,
        "gee_exports_run": False,
    }


