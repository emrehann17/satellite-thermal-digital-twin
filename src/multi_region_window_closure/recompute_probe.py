def recompute_model_and_compare(
    *, frozen_source: Path, probe_root: Path, experiments_root: Optional[Path] = None,
) -> dict[str, Any]:
    """Really fit, really bootstrap, really rebuild the comparison tables."""
    from core.experiment_context import build_experiment_context
    from src.window_closure_sensitivity import (
        DEFAULT_SHIFTS, build_window_variants, canonical_window,
        compute_analysis_id, frozen_input_inventory, normalize_shifts,
        run_compare_stage, run_model_stage, scientific_configuration,
        common_prelabel_interval,
    )

    experiment_id = REFERENCE_AOI
    shifts = normalize_shifts(DEFAULT_SHIFTS)
    context = build_experiment_context(experiment_id)
    canonical = canonical_window(context)
    variants = build_window_variants(context, shifts)
    censor = common_prelabel_interval(variants)
    inventory = frozen_input_inventory(experiment_id, experiments_root, context)
    config = scientific_configuration(
        experiment_id, context, variants, censor, inventory, shifts,
    )
    analysis_id = compute_analysis_id(config)

    model_binding = build_model_binding(
        experiment_id=experiment_id, variants=variants, probe_root=probe_root,
        experiments_root=experiments_root,
    )
    model_outcome = run_model_stage(
        experiment_id, analysis_id, canonical, variants, model_binding,
        output_root=probe_root, experiments_root=experiments_root,
        force=False, resume=False,
    )
    if model_outcome.get("reused"):
        raise RecomputeProbeError(
            "BLOCKER: MODEL_STAGE_WAS_REUSED -- the probe must fit, not reuse."
        )
    compare_binding = build_compare_binding(
        experiment_id=experiment_id, analysis_id=analysis_id,
        probe_root=probe_root, model_binding=model_binding,
    )
    compare_outcome = run_compare_stage(
        experiment_id, analysis_id, variants, compare_binding,
        output_root=probe_root, experiments_root=experiments_root,
        force=False, resume=False,
    )
    if compare_outcome.get("reused"):
        raise RecomputeProbeError(
            "BLOCKER: COMPARE_STAGE_WAS_REUSED -- the probe must rebuild, not reuse."
        )
    metadata = model_outcome["metadata"]
    return {
        "analysis_id": analysis_id,
        "experiment_id": experiment_id,
        "model_fit": bool(metadata.get("model_fit")),
        "bootstrap_run": bool(metadata.get("bootstrap_run")),
        "model_evaluation_count": metadata.get("model_evaluation_count"),
        "model_files_written": len(model_outcome.get("files_written", [])),
        "compare_files_written": len(compare_outcome.get("files_written", [])),
        "model_reused": bool(model_outcome.get("reused")),
        "compare_reused": bool(compare_outcome.get("reused")),
        "model_configuration": metadata.get("model_configuration"),
        "gee_queries_run": False,
        "gee_exports_run": False,
    }


def summarize_existing_probe(
    *, frozen_source: Path, probe_root: Path,
) -> tuple[dict[str, Any], dict[str, Any]]:
    """Re-derive the materialization/recomputation summaries, read-only.

    Used by `--report-only` so the comparison can be rebuilt without refitting.
    Both summaries are read back from what the earlier run actually persisted,
    never assumed.
    """
    frozen_source, probe_root = Path(frozen_source), Path(probe_root)
    experiment_root = probe_root / REFERENCE_AOI
    partition = partition_frozen_source(frozen_source)
    reused = [rel for stage in REUSED_FROZEN_STAGES for rel in partition[stage]]
    excluded = sorted(
        str(rel) for stage in RECOMPUTED_STAGES for rel in partition[stage]
    )
    present = [rel for rel in reused if (experiment_root / rel).is_file()]
    if len(present) != len(reused):
        raise RecomputeProbeError(
            "BLOCKER: PROBE_UPSTREAM_INCOMPLETE -- "
            f"{len(reused) - len(present)} reused upstream artefact(s) are absent."
        )
    metadata = json.loads(
        (experiment_root / "model" / "model_stage_metadata.json").read_text(encoding="utf-8")
    )
    compare_metadata = json.loads(
        (experiment_root / "compare" / "compare_stage_metadata.json").read_text(encoding="utf-8")
    )
    materialization = {
        "probe_root": str(probe_root),
        "experiment_root": str(experiment_root),
        "reused_stages": list(REUSED_FROZEN_STAGES),
        "reused_artifact_count": len(present),
        "reused_artifact_bytes": sum(
            (experiment_root / rel).stat().st_size for rel in present
        ),
        "excluded_frozen_artifact_count": len(excluded),
        "excluded_frozen_artifacts": excluded,
        "recomputed_stages": list(RECOMPUTED_STAGES),
        "gee_queries_run": False,
        "gee_exports_run": False,
        "summarized_from": "existing probe namespace (--report-only)",
    }
    recomputation = {
        "analysis_id": metadata.get("analysis_id"),
        "experiment_id": metadata.get("experiment_id"),
        "model_fit": bool(metadata.get("model_fit")),
        "bootstrap_run": bool(metadata.get("bootstrap_run")),
        "model_evaluation_count": metadata.get("model_evaluation_count"),
        "model_files_written": len(metadata.get("artifact_inventory") or []),
        "compare_files_written": len(compare_metadata.get("output_artifacts") or []),
        "model_reused": False,
        "compare_reused": False,
        "model_configuration": metadata.get("model_configuration"),
        "gee_queries_run": False,
        "gee_exports_run": False,
        "summarized_from": "existing probe namespace (--report-only)",
    }
    return materialization, recomputation


