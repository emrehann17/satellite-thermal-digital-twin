#: Temporary probe namespace. Distinct from the frozen namespace, from the
#: production regional namespace and from the replay namespace.
PROBE_DIAGNOSTIC_NAMESPACE = "window_closure_region_recompute_probe"

PROBE_MODE_ID = "manavgat_local_recomputation_probe.v1"

#: Frozen stages whose artefacts are REUSED (verified copy).
REUSED_FROZEN_STAGES: tuple[str, ...] = ("plan", "export", "local-downstream")

#: Frozen stages that are NEVER copied -- they are recomputed for real.
RECOMPUTED_STAGES: tuple[str, ...] = ("fit", "compare")

#: Top-level frozen sub-trees the probe must not contain before recomputation.
RECOMPUTED_TREES: tuple[str, ...] = ("model", "compare")


class RecomputeProbeError(MultiRegionWindowClosureError):
    """Fail-closed probe condition."""


def probe_output_root(output_root: Optional[Path] = None) -> Path:
    from core.paths import PROJECT_ROOT

    if output_root:
        return Path(output_root)
    return Path(PROJECT_ROOT) / "outputs" / "diagnostics" / PROBE_DIAGNOSTIC_NAMESPACE


def replay_namespace_root(output_root: Optional[Path] = None) -> Optional[Path]:
    """The regional replay namespace produced by the previous turn, if present."""
    from src.multi_region_window_closure.reference_replay import replay_output_root

    aoi_root = replay_output_root(output_root) / REFERENCE_AOI
    if not aoi_root.is_dir():
        return None
    candidates = sorted(
        path for path in aoi_root.glob("*")
        if path.is_dir() and not path.name.startswith("_")
    )
    return candidates[-1] if candidates else None


